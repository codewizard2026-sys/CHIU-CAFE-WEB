-- Run this SQL in Supabase Dashboard → SQL Editor → New query.
create table if not exists public.cafe_reviews (
  id bigint generated by default as identity primary key,
  customer_name text not null check (char_length(trim(customer_name)) between 1 and 60),
  rating integer not null check (rating between 1 and 5),
  review_text text not null check (char_length(trim(review_text)) between 1 and 1000),
  created_at timestamptz not null default now()
);

alter table public.cafe_reviews enable row level security;

-- Anyone can read published reviews and submit a review.
create policy "Public can read cafe reviews"
on public.cafe_reviews for select
to anon, authenticated
using (true);

create policy "Public can submit cafe reviews"
on public.cafe_reviews for insert
to anon, authenticated
with check (
  char_length(trim(customer_name)) between 1 and 60
  and rating between 1 and 5
  and char_length(trim(review_text)) between 1 and 1000
);

grant select, insert on public.cafe_reviews to anon, authenticated;
grant usage, select on sequence public.cafe_reviews_id_seq to anon, authenticated;
